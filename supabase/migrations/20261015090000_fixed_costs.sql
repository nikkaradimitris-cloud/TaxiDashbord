-- =====================================================================
--  Πάγια έξοδα ανά αυτοκίνητο: κόστος άδειας και Ταμείο / ΕΦΚΑ / ΙΚΑ
-- =====================================================================
--  Σταθερά ΜΗΝΙΑΙΑ ποσά: μπαίνουν μία φορά και αλλάζουν όποτε χρειαστεί.
--  Χωριστά για κάθε αυτοκίνητο — κάθε οδηγός έχει δικά του φορολογικά
--  στοιχεία, οπότε τα πάγια του δεν αθροίζονται ποτέ με άλλου οδηγού.
--
--  ΔΕΝ μπαίνουν σε κανέναν υπολογισμό: ούτε στο ταμείο, ούτε στα συνολικά
--  έξοδα, ούτε στο καθαρό κέρδος, ούτε στον ΦΠΑ. Μόνο αποθηκεύονται και
--  φαίνονται στο πάνελ «Πάγια έξοδα» — γι' αυτό η `monthly_summary` και οι
--  υπολογιζόμενες στήλες των βαρδιών μένουν ακριβώς όπως ήταν.
--
--  Κενό = δεν δηλώθηκε ακόμη. Το 0 είναι δηλωμένο ποσό (δεν υπάρχει κόστος).
-- =====================================================================

alter table public.drivers
  add column license_cost numeric(12, 2)
    check (license_cost is null or (license_cost >= 0 and license_cost <= 1000000)),
  add column efka_cost numeric(12, 2)
    check (efka_cost is null or (efka_cost >= 0 and efka_cost <= 1000000));

comment on column public.drivers.license_cost is
  'Κόστος άδειας: μηνιαίο ποσό σε ευρώ. Κενό = δεν δηλώθηκε. Μόνο πληροφοριακό — δεν μπαίνει σε υπολογισμούς.';
comment on column public.drivers.efka_cost is
  'Ταμείο / ΕΦΚΑ / ΙΚΑ: μηνιαίο ποσό σε ευρώ. Κενό = δεν δηλώθηκε. Μόνο πληροφοριακό — δεν μπαίνει σε υπολογισμούς.';

-- Τα ορίζει και τα αλλάζει ο ιδιοκτήτης. Το RLS («drivers_update_owner»,
-- «drivers_select_owner_or_self») κρατά τον περιορισμό: ο οδηγός βλέπει τα
-- δικά του, δεν τα αλλάζει, και κανείς δεν βλέπει άλλου στόλου.
grant insert (license_cost, efka_cost), update (license_cost, efka_cost) on table public.drivers to authenticated;
