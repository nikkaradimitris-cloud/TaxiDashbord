-- =====================================================================
--  Με ποιες εφαρμογές δουλεύει κάθε αυτοκίνητο
-- =====================================================================
--  Κάποιοι οδηγοί δουλεύουν μόνο μία εφαρμογή. Όταν μια εφαρμογή είναι
--  «εκτός» (active = false), η λίστα «Εφαρμογές» δεν ζητά τις εβδομάδες της
--  (δεν χρειάζονται μηδενικά) και η φόρμα δεν τη δείχνει. Το ποσοστό μένει
--  για όταν ξαναμπεί. Το αλλάζουν ο ιδιοκτήτης και ο οδηγός του αυτοκινήτου,
--  όπως και το ποσοστό (ίδιοι κανόνες RLS, ίδια δικαιώματα του πίνακα).
-- =====================================================================

alter table public.platform_rates
  add column active boolean not null default true;
comment on column public.platform_rates.active is
  'Δουλεύει με αυτή την εφαρμογή· false = «εκτός»: χωρίς εβδομάδες που λείπουν και χωρίς επιλογή στη φόρμα.';
